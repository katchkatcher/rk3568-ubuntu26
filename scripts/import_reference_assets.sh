#!/usr/bin/env bash
set -Eeuo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
BR_WORK="${1:?Usage: $0 /path/to/buildroot-work /path/to/rk3568-br-release}"
BR_RELEASE="${2:?Usage: $0 /path/to/buildroot-work /path/to/rk3568-br-release}"
BR_IMAGES="$BR_WORK/output/images"
BR_TARGET="$BR_WORK/output/target"
KVER="6.12.61"
DTB="rk3568-inmys-smarc-evm.dtb"
STAGE="$ROOT/work/reference-import"
REF="$ROOT/reference"

fail() { echo "ERROR: $*" >&2; exit 1; }
for f in "$BR_IMAGES/Image" "$BR_IMAGES/$DTB" \
         "$BR_TARGET/lib/modules/$KVER" \
         "$BR_RELEASE/u-boot-rockchip.bin" \
         "$BR_RELEASE/rk3568_ddr_1332MHz_v1.23.bin" \
         "$BR_RELEASE/rk356x_usbplug_v1.17.bin"; do
    [[ -e "$f" ]] || fail "Не найден обязательный артефакт: $f"
done

mkdir -p "$ROOT/work"
rm -rf "$STAGE"
mkdir -p "$STAGE/kernel" "$STAGE/boot" "$STAGE/modules" "$STAGE/rockchip"

install -m 0644 "$BR_IMAGES/Image" "$STAGE/kernel/Image"
install -m 0644 "$BR_IMAGES/$DTB" "$STAGE/kernel/$DTB"
install -m 0644 "$BR_RELEASE/u-boot-rockchip.bin" "$STAGE/boot/u-boot-rockchip.bin"
install -m 0644 "$BR_RELEASE/rk3568_ddr_1332MHz_v1.23.bin" "$STAGE/rockchip/rk3568_ddr_1332MHz_v1.23.bin"
install -m 0644 "$BR_RELEASE/rk356x_usbplug_v1.17.bin" "$STAGE/rockchip/rk356x_usbplug_v1.17.bin"
cp -a "$BR_TARGET/lib/modules/$KVER" "$STAGE/modules/"
if [[ -d "$BR_TARGET/lib/firmware" ]]; then
    mkdir -p "$STAGE/firmware"
    cp -a "$BR_TARGET/lib/firmware/." "$STAGE/firmware/"
fi

cat > "$STAGE/REFERENCE-INFO.txt" <<INFO
Reference assets for NMS-SM-RK3568 Ubuntu image build
Kernel version: $KVER
Device tree: $DTB
U-Boot and Rockchip Maskrom loaders: copied from rk3568-br-release
Kernel Image, DTB, modules and firmware: copied from Buildroot output
The Buildroot rootfs.ext2, full br_2024.02_rk3568.dd image, mbr.dat and burn.sh
are intentionally not included: the Ubuntu image builder does not consume them.
Partition table is generated by build_images.sh using sfdisk; U-Boot and loader
binaries are the reference boot components used by this project.
INFO

rm -rf "$REF"
mv "$STAGE" "$REF"
(
    cd "$REF"
    find . -type f ! -name SHA256SUMS -print0 | sort -z | xargs -0 sha256sum > SHA256SUMS
)

echo "Reference assets imported into: $REF"
echo "Verify them with: (cd reference && sha256sum -c SHA256SUMS)"
